export default function LedText({ text = "", color = "currentColor", size = "small" }) {
  const isWord = /[a-zA-Z]/.test(text);
  const pitchX = isWord ? 4 : 5;
  const pitchY = 4;
  const radius = size === "large" ? 2.32 : 1.8;
  const scale = size === "large" ? 1.5 : 1;

  let circles = [];
  let currentX = 0;

  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    const glyph = GLYPHS[char] || GLYPHS[" "];
    
    let maxCols = 0;
    
    glyph.forEach((rowStr, y) => {
      if (rowStr.length > maxCols) maxCols = rowStr.length;
      for (let col = 0; col < rowStr.length; col++) {
        if (rowStr[col] === '1') {
          circles.push(
            <circle 
              key={`${i}-${y}-${col}`}
              cx={currentX + (col * pitchX) + 1.55} 
              cy={(y * pitchY) + 1.55} 
              r={radius} 
            />
          );
        }
      }
    });
    
    currentX += (maxCols * pitchX) + 2; // Add gap between letters
  }

  const viewBoxWidth = currentX;
  
  return (
    <svg 
      viewBox={`0 0 ${viewBoxWidth} 28`} 
      style={{ 
        display: 'inline-block', 
        height: `${28 * scale}px`,
        fill: color,
        overflow: 'visible'
      }}
    >
      {circles}
    </svg>
  );
}
